      SCORE_WARMUP_ROUNDS=${FED_WALKER2D_SCORE_WARMUP_ROUNDS:-2}
      SCORE_WARMUP_NORMALIZATION=${FED_WALKER2D_SCORE_WARMUP_NORMALIZATION:-batch_zscore}
      INJECTION_WARMUP_ROUNDS=${FED_WALKER2D_INJECTION_WARMUP_ROUNDS:-2}
      ARCHIVE_STD_PENALTY=${FED_WALKER2D_ARCHIVE_STD_PENALTY:-0.25}
      INJECT_STD_PENALTY=${FED_WALKER2D_INJECT_STD_PENALTY:-0.25}
      STAGNATION_PATIENCE=${FED_WALKER2D_STAGNATION_PATIENCE:-8}
      STAGNATION_MAX_BOOSTS=${FED_WALKER2D_STAGNATION_MAX_BOOSTS:-2}
      STAGNATION_BOOST_COOLDOWN=${FED_WALKER2D_STAGNATION_BOOST_COOLDOWN:-12}
      ENV_CLIENT_HETEROGENEITY=${FED_WALKER2D_CLIENT_HETEROGENEITY:-0.30}
      ENV_CLIENT_HETEROGENEITY_MODE=${FED_WALKER2D_CLIENT_HETEROGENEITY_MODE:-env_params_only}
      WALKER_HEALTHY_REWARD=${FED_WALKER2D_HEALTHY_REWARD:-0.05}
      WALKER_FORWARD_REWARD_WEIGHT=${FED_WALKER2D_FORWARD_REWARD_WEIGHT:-1.0}
      THIS_BASELINE_UPDATE_TO_DATA_RATIO=${BASELINE_WALKER2D_UPDATE_TO_DATA_RATIO:-0.25}
      THIS_BASELINE_MAX_UPDATES_PER_ROUND=${BASELINE_WALKER2D_MAX_UPDATES_PER_ROUND:-256}
      THIS_BASELINE_BASE_UPDATES=${BASELINE_WALKER2D_BASE_UPDATES:-64}
      THIS_BASELINE_ACTOR_LR=${BASELINE_WALKER2D_ACTOR_LR:-0.0001}
      THIS_BASELINE_POST_SYNC_CRITIC_WARMUP=${BASELINE_WALKER2D_POST_SYNC_CRITIC_WARMUP:-32}
      ;;
  esac
  CLIENTS=${FED_NUM_CLIENTS:-3}
  WORKERS=${FED_NUM_WORKERS:-$CLIENTS}
  if [[ -n "$TARGET_ENV_STEPS" ]]; then
    TARGET_STEPS=$TARGET_ENV_STEPS
  elif [[ "$BUDGET_PRESET" == "converged" ]]; then
    case "$ENV_NAME" in
      Swimmer-v5) TARGET_STEPS=${FED_SWIMMER_TARGET_ENV_STEPS:-1200000} ;;
      Pusher-v5) TARGET_STEPS=${FED_PUSHER_TARGET_ENV_STEPS:-300000} ;;
      Walker2d-v5) TARGET_STEPS=${FED_WALKER2D_TARGET_ENV_STEPS:-1200000} ;;
      Hopper-v5) TARGET_STEPS=${FED_HOPPER_TARGET_ENV_STEPS:-1200000} ;;
      *) TARGET_STEPS=1200000 ;;
    esac
  else
    TARGET_STEPS=459000
  fi
  if [[ -n "${BASELINE_ROUNDS:-}" ]]; then
    THIS_BASELINE_ROUNDS="$BASELINE_ROUNDS"
  else
    THIS_BASELINE_ROUNDS=$(python3 - <<PY
import math
print(max(1, math.ceil(int('$TARGET_STEPS') / max(1, int('$CLIENTS') * int('$STEPS')))))
PY
)
  fi
  echo "$ENV_NAME continuous budget=$BUDGET_PRESET target_env_steps=$TARGET_STEPS baseline_rounds>=$THIS_BASELINE_ROUNDS heterogeneity=$ENV_CLIENT_HETEROGENEITY/$ENV_CLIENT_HETEROGENEITY_MODE"

  SEED_SLOT=0
  for SEED in $SEEDS; do
    EXP_SUFFIX=""
    if [[ -n "$REPEAT_ID" ]]; then
      EXP_SUFFIX="_r${REPEAT_ID}"
    fi
    for VARIANT in $FED_VARIANTS; do
      EXP="fedevosac_${ENV_NAME}_${VARIANT}_s${SEED}${EXP_SUFFIX}"
      if [[ "$SKIP_EXISTING" == "1" ]] && run_is_complete "$LOG_DIR/$EXP/metrics.csv" "$TARGET_STEPS"; then
        echo "Skip complete run: $EXP"
        continue
      fi
      EXTRA_FED_ARGS=()
      if [[ "$EA_MUTATE_BIAS" == "1" ]]; then
        EXTRA_FED_ARGS+=(--ea-mutate-bias)
      fi
      if [[ "$EA_FREEZE_SAC_LOG_STD" == "1" ]]; then
        EXTRA_FED_ARGS+=(--ea-freeze-sac-log-std)
      fi
      python3 -m src.main \
        --env "$ENV_NAME" \
        --mode fed_evo_rl \
        --fed-ablation "$VARIANT" \
        --algorithm SAC \
        --population-size "$POP" \
        --num-workers "$WORKERS" \
        --num-clients "$CLIENTS" \
        --max-generations "$GENS" \
        --target-env-steps "$TARGET_STEPS" \
        --max-episode-steps "$STEPS" \
        --client-heterogeneity "$ENV_CLIENT_HETEROGENEITY" \
        --client-heterogeneity-mode "$ENV_CLIENT_HETEROGENEITY_MODE" \
        --walker-healthy-reward "$WALKER_HEALTHY_REWARD" \
        --walker-forward-reward-weight "$WALKER_FORWARD_REWARD_WEIGHT" \
        --fed-aggregation softmax \
        --fed-aggregation-interval "$FED_AGG_INTERVAL" \
        --fed-aggregation-temperature "$AGGREGATION_TEMPERATURE" \
        --fed-raw-softmax-temperature "$RAW_SOFTMAX_TEMPERATURE" \
        --fed-score-normalization "$SCORE_NORMALIZATION" \
        --fed-score-warmup-rounds "$SCORE_WARMUP_ROUNDS" \
        --fed-score-warmup-normalization "$SCORE_WARMUP_NORMALIZATION" \
        --fed-score-ema-beta "$FED_SCORE_EMA_BETA" \
        --fed-score-min-std "$FED_SCORE_MIN_STD" \
        --fed-score-scale "$SCORE_SCALE" \
        --fed-injection-warmup-rounds "$INJECTION_WARMUP_ROUNDS" \
        --fed-inject-margin "$INJECT_MARGIN" \
        --inject-noise "$INJECT_NOISE" \
        --migration-blend "$MIGRATION_BLEND" \
        --fed-delta-clip-norm "$DELTA_CLIP_NORM" \
        --ea-mutation-prob "$EA_MUTATION_PROB" \
        --ea-mutation-scale-mode "$EA_MUTATION_SCALE_MODE" \
        --ea-mutation-scale-floor "$EA_MUTATION_SCALE_FLOOR" \
        --ea-prob-reset-and-super "$EA_RESET_PROB" \
        --ea-init-mode "$EA_INIT_MODE" \
        --ea-init-seed "$EA_INIT_SEED" \
        --ea-init-noise-scale "$EA_INIT_NOISE_SCALE" \
        --ea-weight-clip 5 \
        --elite-archive-size 5 \
        --elite-archive-restore-copies 1 \
        --archive-eval-candidates "$ARCHIVE_EVAL_CANDIDATES" \
        --archive-eval-episodes "$ARCHIVE_EVAL_EPISODES" \
        --archive-std-penalty "$ARCHIVE_STD_PENALTY" \
        --fed-inject-std-penalty "$INJECT_STD_PENALTY" \
        --client-rollouts "$CLIENT_ROLLOUTS" \
        --client-updates "$CLIENT_UPDATES" \
        --client-critic-warmup-updates "$CLIENT_CRITIC_WARMUP" \
        --client-actor-lr "$CLIENT_ACTOR_LR" \
        --client-validation-episodes "$CLIENT_VALIDATION_EPISODES" \
        --client-rollback-margin "$CLIENT_ROLLBACK_MARGIN" \
        --batch-size 64 \
        --eval-episodes "$EVAL_EPISODES" \
        --seed "$SEED" \
        --repeat-id "$REPEAT_ID" \
        --seed-slot "$SEED_SLOT" \
        --stagnation-patience "$STAGNATION_PATIENCE" \
        --stagnation-min-delta "$STAGNATION_MIN_DELTA" \
        --stagnation-max-boosts "$STAGNATION_MAX_BOOSTS" \
        --stagnation-boost-cooldown "$STAGNATION_BOOST_COOLDOWN" \
        --immigrant-fraction "$IMMIGRANT_FRACTION" \
        --log-dir "$LOG_DIR" \
        --exp-name "$EXP" \
        "${EXTRA_FED_ARGS[@]}"
    done
    for MODE in $SAC_BASELINES; do
      EXP="${MODE}_${ENV_NAME}_s${SEED}${EXP_SUFFIX}"
      if [[ "$SKIP_EXISTING" == "1" ]] && run_is_complete "$SAC_LOG_DIR/$EXP/metrics.csv" "$TARGET_STEPS"; then
        echo "Skip complete run: $EXP"
        continue
      fi
      python3 scripts/train_continuous_sac_baseline.py \
        --env "$ENV_NAME" \
        --seed "$SEED" \
        --repeat-id "$REPEAT_ID" \
        --seed-slot "$SEED_SLOT" \
        --rounds "$THIS_BASELINE_ROUNDS" \
        --target-env-steps "$TARGET_STEPS" \
        --num-workers "$CLIENTS" \
        --updates "$THIS_BASELINE_BASE_UPDATES" \
        --update-to-data-ratio "$THIS_BASELINE_UPDATE_TO_DATA_RATIO" \
        --max-updates-per-round "$THIS_BASELINE_MAX_UPDATES_PER_ROUND" \
        --actor-lr "$THIS_BASELINE_ACTOR_LR" \
        --post-sync-critic-warmup-updates "$THIS_BASELINE_POST_SYNC_CRITIC_WARMUP" \
        --aggregation-interval "$BASELINE_AGGREGATION_INTERVAL" \
        --server-learning-rate "$BASELINE_SERVER_LEARNING_RATE" \
        --aggregation-eval-episodes "$ARCHIVE_EVAL_EPISODES" \
        --eval-interval "$BASELINE_AGGREGATION_INTERVAL" \
        --batch-size 64 \
        --eval-episodes "$EVAL_EPISODES" \
        --max-episode-steps "$STEPS" \
        --client-heterogeneity "$ENV_CLIENT_HETEROGENEITY" \
        --client-heterogeneity-mode "$ENV_CLIENT_HETEROGENEITY_MODE" \
        --walker-healthy-reward "$WALKER_HEALTHY_REWARD" \
        --walker-forward-reward-weight "$WALKER_FORWARD_REWARD_WEIGHT" \
        --log-dir "$SAC_LOG_DIR" \
        --exp-name "$EXP" \
        --baseline-mode "$MODE"
    done
    SEED_SLOT=$((SEED_SLOT + 1))
  done
done

