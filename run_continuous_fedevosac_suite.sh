run_is_complete() {
  local metrics_path=$1
  local target_steps=$2
  [[ -s "$metrics_path" ]] || return 1
  awk -F, -v target="$target_steps" '
    NR == 1 {
      for (i = 1; i <= NF; i++) if ($i == "total_env_steps") step_col = i
      next
    }
    step_col && $step_col != "" { last = $step_col + 0 }
    END { exit !(last >= target) }
  ' "$metrics_path"
}

